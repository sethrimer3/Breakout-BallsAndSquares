import { GROWTH, growthRateAt } from "../config";
import type { Rng } from "../core/Rng";
import type { Soldier } from "../entities/Soldier";
import { cellOverlapsCircle, circleIsClear } from "../systems/PhysicsSystem";
import { Frontier } from "./Frontier";
import type { PixelWorld } from "./PixelWorld";

export interface GrowthEvents {
  onGrow?(cx: number, cy: number): void;
  onSoldierKilled?(soldier: Soldier, cx: number, cy: number): void;
  onSoldierRescued?(soldier: Soldier, fromCx: number, fromCy: number, toCx: number, toCy: number, hpCost: number): void;
  onBlightExplode?(cx: number, cy: number, radiusCells: number, damage: number): void;
}

interface PendingExplosion {
  cx: number;
  cy: number;
  timer: number;
  radius: number;
  damage: number;
}

const DX = [1, -1, 0, 0];
const DY = [0, 0, 1, -1];

/**
 * Hostile terrain replication. Solid frontier cells copy into empty cardinal
 * neighbors at an escalating rate; overlapping soldiers die immediately.
 */
export class GrowthSystem {
  readonly frontier: Frontier;
  /** Ring buffer of recently grown cells (for crimson pulse rendering). */
  readonly glowIndex = new Int32Array(GROWTH.glowCap);
  readonly glowTime = new Float32Array(GROWTH.glowCap);
  glowHead = 0;
  glowCount = 0;

  rate = 0;
  /** Total pink blight sub-pixel generation rate across all exposed living Blight Cores (`exposedCores * rate`). */
  coreRate = 0;
  /** Number of living Blight Cores currently exposed to open air via their connected pink blight. */
  exposedCoresCount = 0;
  graceSeconds = GROWTH.graceSeconds;
  startRate = GROWTH.baseRate;
  rateMultiplier = 1;
  weakenChance = 0;
  explosiveChance = 0;
  explosiveDamage = 1;
  explosiveRadius = 1.2;
  readonly pendingExplosions: PendingExplosion[] = [];
  /** Cumulative seconds subtracted from the blight timer by destroying Blight Cores. */
  timeOffset = 0;
  coresDestroyed = 0;
  totalEvents = 0;
  /** Total 50%-smaller pink blight sub-pixels generated by Blight Cores. */
  totalSubBlightEvents = 0;
  nearEventsTotal = 0;
  private acc = 0;
  /** Per-core accumulator (`accByCore[coreId - 1]`) so each living Blight Core acts as its own independent generator. */
  private coreAcc: number[] = [];
  /** Reusable BFS buffers for connected pink blight + core component discovery. */
  private bfsStamp: Uint32Array;
  private curStamp = 0;
  private bfsQueue: Int32Array;
  private perimBuf: number[] = [];
  private memberBuf: number[] = [];
  private coreProcessed = new Uint8Array(0);
  /** Rolling telemetry ring (time, 1 if near soldier else 0). */
  private telTime: number[] = [];
  private telNear: number[] = [];

  constructor(
    private world: PixelWorld,
    private rng: Rng,
    private events: GrowthEvents = {},
  ) {
    this.frontier = new Frontier(world);
    const subN = world.subWidth * world.subHeight;
    this.bfsStamp = new Uint32Array(subN);
    this.bfsQueue = new Int32Array(subN);
  }

  reset(): void {
    this.frontier.seedFromRoom();
    this.rate = 0;
    this.coreRate = 0;
    this.exposedCoresCount = 0;
    this.acc = 0;
    this.coreAcc = this.world.blightCores.map(() => 0);
    this.timeOffset = 0;
    this.coresDestroyed = 0;
    this.totalEvents = 0;
    this.totalSubBlightEvents = 0;
    this.nearEventsTotal = 0;
    this.glowHead = 0;
    this.glowCount = 0;
    this.telTime.length = 0;
    this.telNear.length = 0;
    this.pendingExplosions.length = 0;
  }

  /** Effective blight timer (seconds) after accounting for upgrade grace and destroyed Blight Cores. */
  effectiveBlightTime(runTime: number): number {
    return Math.max(0, runTime - (this.graceSeconds - GROWTH.graceSeconds) - this.timeOffset);
  }

  /**Remaining seconds before blight starts/resumes replicating (0 if already active). */
  graceRemaining(runTime: number): number {
    const shifted = runTime - (this.graceSeconds - GROWTH.graceSeconds) - this.timeOffset;
    return Math.max(0, GROWTH.graceSeconds - shifted);
  }

  /**
   * Called when the player destroys a Blight Core: reduces the blight timer
   * by `seconds` (default `GROWTH.coreKillTimeReduction`) and immediately
   * recalculates the blight replication rate.
   */
  reduceBlightTimer(runTime: number, seconds = GROWTH.coreKillTimeReduction): void {
    this.timeOffset += seconds;
    this.coresDestroyed++;
    this.acc = 0;
    const shiftedTime = runTime - (this.graceSeconds - GROWTH.graceSeconds) - this.timeOffset;
    this.rate = growthRateAt(shiftedTime, this.startRate) * this.rateMultiplier;
  }

  /** Rolling percentage (0..100) of growth events within `nearRadiusCells` of a living soldier. */
  nearSoldierPercent(now: number): number {
    this.pruneTelemetry(now);
    if (this.telNear.length === 0) return 0;
    let s = 0;
    for (let i = 0; i < this.telNear.length; i++) s += this.telNear[i];
    return (s / this.telNear.length) * 100;
  }

  private pruneTelemetry(now: number): void {
    const cutoff = now - GROWTH.telemetryWindow;
    while (this.telTime.length > 0 && this.telTime[0] < cutoff) {
      this.telTime.shift();
      this.telNear.shift();
    }
  }

  update(dt: number, runTime: number, soldiers: readonly Soldier[]): void {
    // Process pending explosive blight detonations
    let pIdx = 0;
    while (pIdx < this.pendingExplosions.length) {
      const exp = this.pendingExplosions[pIdx];
      exp.timer -= dt;
      if (exp.timer <= 0) {
        this.pendingExplosions.splice(pIdx, 1);
        if (this.world.inBounds(exp.cx, exp.cy)) {
          this.events.onBlightExplode?.(exp.cx, exp.cy, exp.radius, exp.damage);
        }
      } else {
        pIdx++;
      }
    }

    const shiftedTime = runTime - (this.graceSeconds - GROWTH.graceSeconds) - this.timeOffset;
    this.rate = growthRateAt(shiftedTime, this.startRate) * this.rateMultiplier;
    if (this.rate <= 0) {
      this.coreRate = 0;
      this.exposedCoresCount = 0;
      return;
    }

    // 1) Normal terrain frontier replication.
    if (this.frontier.size > 0) {
      this.acc += this.rate * dt;
      let steps = 0;
      while (this.acc >= 1 && steps < GROWTH.maxEventsPerStep && this.frontier.size > 0) {
        if (this.replicateOne(runTime, soldiers)) {
          this.acc -= 1;
        } else {
          // Could not find a valid source after retries; drop fractional pressure.
          this.acc = 0;
          break;
        }
        steps++;
      }
      if (this.acc > GROWTH.maxEventsPerStep) this.acc = GROWTH.maxEventsPerStep;
    }

    // 2) Blight Core pink sub-pixel generators:
    // Every living Blight Core acts as its own generator producing `this.rate` 50%-smaller pink
    // blight sub-pixels per second around the open-air perimeter of its connected pink blight.
    // Multiple cores connected together through pink blight compound (`k * this.rate` around the shared perimeter).
    this.updateCoreGenerators(dt, runTime, soldiers);
  }

  /**
   * Tick all living Blight Core generators. If `k` living cores are connected together
   * via pink blight (or adjacent core cells), their connected component receives `k * rate * dt`
   * sub-pixel growth events distributed randomly around the component's open-air perimeter.
   */
  updateCoreGenerators(dt: number, runTime: number, soldiers: readonly Soldier[]): void {
    const cores = this.world.blightCores;
    if (!cores || cores.length === 0 || this.rate <= 0) {
      this.coreRate = 0;
      this.exposedCoresCount = 0;
      return;
    }
    while (this.coreAcc.length < cores.length) this.coreAcc.push(0);

    // Each living core is its own generator: it banks `rate * dt` sub-pixels per step.
    let anyDue = false;
    for (let i = 0; i < cores.length; i++) {
      if (!cores[i].alive) {
        this.coreAcc[i] = 0;
        continue;
      }
      this.coreAcc[i] += this.rate * dt;
      if (this.coreAcc[i] >= 1) anyDue = true;
    }
    // Nothing to place this step: keep last step's exposure telemetry.
    if (!anyDue) return;

    // Group living cores into connected components (cores touching each other or
    // linked through pink blight). A component with k cores spends all k banks
    // around its shared open-air perimeter, so connected cores compound.
    const processed = this.coreProcessed.length >= cores.length ? this.coreProcessed : (this.coreProcessed = new Uint8Array(cores.length * 2));
    processed.fill(0);
    const perim = this.perimBuf;
    const members = this.memberBuf;
    let exposed = 0;
    for (let i = 0; i < cores.length; i++) {
      if (!cores[i].alive || processed[i]) continue;
      this.collectComponent(cores[i].id, perim, members);
      let total = 0;
      for (let m = 0; m < members.length; m++) {
        processed[members[m] - 1] = 1;
        total += this.coreAcc[members[m] - 1];
      }
      if (perim.length === 0) {
        // Sealed in solid terrain: generators idle until soldiers expose them.
        for (let m = 0; m < members.length; m++) this.coreAcc[members[m] - 1] = 0;
        continue;
      }
      exposed += members.length;
      const cap = GROWTH.maxEventsPerStep * members.length;
      const n = Math.min(Math.floor(total), cap, perim.length);
      for (let e = 0; e < n; e++) {
        // Random perimeter subcell, without replacement so one step never stacks.
        const k = this.rng.int(perim.length);
        const si = perim[k];
        perim[k] = perim[perim.length - 1];
        perim.length--;
        this.growSubPixel(si, runTime, soldiers);
      }
      // Spread the leftover fractional pressure back over the member cores.
      const share = Math.min(GROWTH.maxEventsPerStep, (total - n) / members.length);
      for (let m = 0; m < members.length; m++) this.coreAcc[members[m] - 1] = share;
    }
    this.exposedCoresCount = exposed;
    this.coreRate = exposed * this.rate;
  }

  /** True if subcell `(sx, sy)` is part of a living Blight Core or has pink sub-blight (`subHealth > 0`). */
  private isPinkOrCoreSubcell(sx: number, sy: number): boolean {
    const w = this.world;
    if (w.subHealth[sy * w.subWidth + sx] > 0) return true;
    const cx = sx >> 1;
    const cy = sy >> 1;
    const idx = cy * w.width + cx;
    return w.coreId[idx] > 0 && w.health[idx] > 0;
  }

  /**
   * Flood the connected pink blight + living core component that contains `coreId`.
   * Fills `outPerimeter` with every open-air subcell touching it, and `outMembers`
   * with the ids of every living core in it (including `coreId`).
   */
  collectComponent(coreId: number, outPerimeter: number[], outMembers: number[]): void {
    outPerimeter.length = 0;
    outMembers.length = 0;
    const w = this.world;
    const core = w.blightCores[coreId - 1];
    if (!core || !core.alive) return;
    outMembers.push(coreId);

    if ((this.curStamp = (this.curStamp + 1) >>> 0) === 0) {
      this.bfsStamp.fill(0);
      this.curStamp = 1;
    }
    const stamp = this.curStamp;
    const visited = this.bfsStamp;
    const queue = this.bfsQueue;
    const sw = w.subWidth;
    const sh = w.subHeight;
    let head = 0;
    let tail = 0;

    // Seed BFS with the subcells of all surviving normal cells of `core`.
    for (let k = 0; k < core.cells.length; k++) {
      const cellIdx = core.cells[k];
      if (w.health[cellIdx] === 0) continue;
      const cx = cellIdx % w.width;
      const cy = Math.floor(cellIdx / w.width);
      for (let dy = 0; dy < 2; dy++) {
        for (let dx = 0; dx < 2; dx++) {
          const sx = cx * 2 + dx;
          const sy = cy * 2 + dy;
          const si = sy * sw + sx;
          if (visited[si] !== stamp) {
            visited[si] = stamp;
            queue[tail++] = si;
          }
        }
      }
    }

    while (head < tail) {
      const cur = queue[head++];
      const sx = cur % sw;
      const sy = (cur - sx) / sw;
      for (let d = 0; d < 4; d++) {
        const nx = sx + DX[d];
        const ny = sy + DY[d];
        if (nx < 0 || ny < 0 || nx >= sw || ny >= sh) continue;
        const ni = ny * sw + nx;
        if (visited[ni] === stamp) continue;

        if (this.isPinkOrCoreSubcell(nx, ny)) {
          visited[ni] = stamp;
          queue[tail++] = ni;
          const cid = w.coreId[(ny >> 1) * w.width + (nx >> 1)];
          if (cid > 0 && w.blightCores[cid - 1]?.alive && outMembers.indexOf(cid) < 0) outMembers.push(cid);
        } else if (!w.subSolidAt(nx, ny)) {
          // Open air subcell on the outer perimeter of this connected pink blight!
          visited[ni] = stamp;
          outPerimeter.push(ni);
        }
      }
    }
  }

  /** True if the Blight Core `coreId` (or its connected pink blight) touches at least one open-air subcell. */
  isCoreExposed(coreId: number): boolean {
    this.collectComponent(coreId, this.perimBuf, this.memberBuf);
    return this.perimBuf.length > 0;
  }

  /** Grow one 50%-smaller pink blight sub-pixel into open-air subcell index `destSub`. */
  private growSubPixel(destSub: number, runTime: number, soldiers: readonly Soldier[]): void {
    const w = this.world;
    const sx = destSub % w.subWidth;
    const sy = Math.floor(destSub / w.subWidth);
    const hp =
      this.weakenChance > 0 && this.rng.next() < this.weakenChance
        ? 1
        : w.maxSubHealthAt(sx, sy);

    w.subTint[destSub] = this.rng.int(256);
    w.setSubCell(sx, sy, hp, "grown");

    const cx = sx >> 1;
    const cy = sy >> 1;
    const parentIdx = cy * w.width + cx;
    this.recordGlow(parentIdx, runTime);
    this.recordTelemetry(cx, cy, runTime, soldiers);
    this.totalEvents++;
    this.totalSubBlightEvents++;
    this.events.onGrow?.(cx, cy);

    // Kill or rescue any soldier whose collision circle overlaps the newly grown 50% sub-pixel.
    const subCs = w.subCellSize;
    for (let i = 0; i < soldiers.length; i++) {
      const s = soldiers[i];
      if (s.alive && cellOverlapsCircle(subCs, sx, sy, s.x, s.y, s.radius)) {
        if (!this.tryRescueSoldier(s, cx, cy)) {
          s.alive = false;
          this.events.onSoldierKilled?.(s, cx, cy);
        }
      }
    }

    if (this.explosiveChance > 0 && this.rng.next() < this.explosiveChance) {
      this.pendingExplosions.push({
        cx,
        cy,
        timer: this.rng.range(0.2, 0.45),
        radius: this.explosiveRadius,
        damage: this.explosiveDamage,
      });
    }
  }

  /** Execute one copy event. Returns true on success. */
  replicateOne(runTime: number, soldiers: readonly Soldier[]): boolean {
    const w = this.world;
    const f = this.frontier;

    if (f.size === 0) {
      const dx = w.centerX;
      const dy = w.centerY;
      const dest = dy * w.width + dx;
      const hp = this.weakenChance > 0 && this.rng.next() < this.weakenChance ? 1 : w.maxHealthAt(dx, dy);
      w.setCell(dx, dy, hp, "grown");
      w.decor[dest] = 0;
      this.recordGlow(dest, runTime);
      this.recordTelemetry(dx, dy, runTime, soldiers);
      this.totalEvents++;
      this.events.onGrow?.(dx, dy);

      if (this.explosiveChance > 0 && this.rng.next() < this.explosiveChance) {
        this.pendingExplosions.push({
          cx: dx,
          cy: dy,
          timer: this.rng.range(0.2, 0.45),
          radius: this.explosiveRadius,
          damage: this.explosiveDamage,
        });
      }
      return true;
    }

    const neighbors: number[] = [];
    for (let attempt = 0; attempt < 8 && f.size > 0; attempt++) {
      const src = this.pickSource(soldiers);
      const sx = src % w.width;
      const sy = Math.floor(src / w.width);
      neighbors.length = 0;
      for (let d = 0; d < 4; d++) {
        const nx = sx + DX[d];
        const ny = sy + DY[d];
        // Pink core blight stays pink: normal blight only grows into fully open cells.
        if (w.inBounds(nx, ny) && !w.anySolidInCell(nx, ny)) {
          neighbors.push(ny * w.width + nx);
        }
      }
      if (neighbors.length === 0) {
        f.remove(src);
        continue;
      }
      const dest = neighbors[this.rng.int(neighbors.length)];
      const dx = dest % w.width;
      const dy = Math.floor(dest / w.width);
      const hp =
        this.weakenChance > 0 && this.rng.next() < this.weakenChance
          ? 1
          : w.maxHealthAt(dx, dy);
      w.setCell(dx, dy, hp, "grown");
      // Copy tint with a slight variation from parent.
      w.tint[dest] = (w.tint[src] + this.rng.int(17) - 8) & 255;
      // Blight overwrites whatever the facility had here.
      w.decor[dest] = 0;
      this.recordGlow(dest, runTime);
      this.recordTelemetry(dx, dy, runTime, soldiers);
      this.totalEvents++;
      this.events.onGrow?.(dx, dy);

      if (this.explosiveChance > 0 && this.rng.next() < this.explosiveChance) {
        this.pendingExplosions.push({
          cx: dx,
          cy: dy,
          timer: this.rng.range(0.2, 0.45),
          radius: this.explosiveRadius,
          damage: this.explosiveDamage,
        });
      }

      // Kill or rescue any soldier whose collision circle overlaps the new cell.
      const cs = w.cellSize;
      for (let i = 0; i < soldiers.length; i++) {
        const s = soldiers[i];
        if (s.alive && cellOverlapsCircle(cs, dx, dy, s.x, s.y, s.radius)) {
          if (!this.tryRescueSoldier(s, dx, dy)) {
            s.alive = false;
            this.events.onSoldierKilled?.(s, dx, dy);
          }
        }
      }
      return true;
    }
    return false;
  }

  /**
   * Attempt to rescue a soldier enclosed by blight using soldier health.
   * Costs 1 HP per block needed to travel to the nearest open space.
   * Returns true if rescued, false if health was insufficient (soldier dies).
   */
  private tryRescueSoldier(s: Soldier, originCx: number, originCy: number): boolean {
    if (s.health <= 0 || s.maxHealth <= 0) return false;
    const w = this.world;
    const cs = w.cellSize;
    const maxDist = Math.min(30, s.health);
    let bestDist = Infinity;
    let bestX = 0;
    let bestY = 0;
    let bestCost = Infinity;

    // Search outward in rings for the nearest open cell where the soldier fits.
    for (let rad = 1; rad <= maxDist; rad++) {
      for (let dy = -rad; dy <= rad; dy++) {
        for (let dx = -rad; dx <= rad; dx++) {
          if (Math.max(Math.abs(dx), Math.abs(dy)) !== rad) continue;
          const cx = originCx + dx;
          const cy = originCy + dy;
          if (!w.inBounds(cx, cy)) continue;
          if (w.solidAt(cx, cy) || w.anySolidInCell(cx, cy)) continue;
          const px = (cx + 0.5) * cs;
          const py = (cy + 0.5) * cs;
          if (!circleIsClear(w, px, py, s.radius)) continue;
          const distBlocks = Math.hypot(dx, dy);
          const cost = Math.max(1, Math.round(distBlocks));
          if (cost <= s.health && distBlocks < bestDist) {
            bestDist = distBlocks;
            bestCost = cost;
            bestX = px;
            bestY = py;
          }
        }
      }
      if (bestDist < Infinity) break;
    }

    if (bestDist < Infinity && bestCost <= s.health) {
      s.health -= bestCost;
      s.x = bestX;
      s.y = bestY;
      s.stuckFrames = 0;
      const destCx = Math.floor(bestX / cs);
      const destCy = Math.floor(bestY / cs);
      this.events.onSoldierRescued?.(s, originCx, originCy, destCx, destCy, bestCost);
      return true;
    }

    return false;
  }

  private pickSource(soldiers: readonly Soldier[]): number {
    const f = this.frontier;
    if (GROWTH.localBias > 0 && this.rng.next() < GROWTH.localBias) {
      const alive = soldiers.filter((s) => s.alive);
      if (alive.length > 0) {
        const s = alive[this.rng.int(alive.length)];
        const scx = Math.floor(s.x / this.world.cellSize);
        const scy = Math.floor(s.y / this.world.cellSize);
        const R = GROWTH.localRadiusCells;
        for (let k = 0; k < GROWTH.localSamples; k++) {
          const cx = scx + this.rng.int(R * 2 + 1) - R;
          const cy = scy + this.rng.int(R * 2 + 1) - R;
          if (f.has(cx, cy)) return cy * this.world.width + cx;
        }
      }
    }
    return f.list[this.rng.int(f.size)];
  }

  private recordGlow(cellIndex: number, runTime: number): void {
    this.glowIndex[this.glowHead] = cellIndex;
    this.glowTime[this.glowHead] = runTime;
    this.glowHead = (this.glowHead + 1) % GROWTH.glowCap;
    if (this.glowCount < GROWTH.glowCap) this.glowCount++;
  }

  private recordTelemetry(cx: number, cy: number, runTime: number, soldiers: readonly Soldier[]): void {
    const cs = this.world.cellSize;
    const r = GROWTH.nearRadiusCells;
    let near = 0;
    for (let i = 0; i < soldiers.length; i++) {
      const s = soldiers[i];
      if (!s.alive) continue;
      const sx = Math.floor(s.x / cs);
      const sy = Math.floor(s.y / cs);
      if (Math.max(Math.abs(cx - sx), Math.abs(cy - sy)) <= r) {
        near = 1;
        break;
      }
    }
    if (near) this.nearEventsTotal++;
    this.telTime.push(runTime);
    this.telNear.push(near);
    this.pruneTelemetry(runTime);
  }
}
