export type SpriteName = keyof typeof SPRITES;

function hexToRgb(hex: string): [number, number, number] {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function mix(a: [number, number, number], b: [number, number, number], t: number): string {
  const c = a.map((v, i) => Math.round(v + (b[i] - v) * t));
  return `rgb(${c[0]},${c[1]},${c[2]})`;
}

/** Resolve one grid character to a CSS color (null = transparent). */
export function paletteColor(ch: string, tint: string): string | null {
  const base = hexToRgb(tint);
  switch (ch) {
    case "#":
      return mix(base, base, 0);
    case "+":
      return mix(base, [255, 255, 255], 0.45);
    case "-":
      return mix(base, [0, 0, 0], 0.5);
    case "w":
      return "#ffffff";
    case "k":
      return "#070b12";
    default:
      return null;
  }
}

const urlCache = new Map<string, string>();

/** 1:1 PNG data URL of a tinted sprite (cached per sprite + tint). */
export function spriteUrl(name: SpriteName, tint: string): string {
  const key = `${name}|${tint}`;
  const hit = urlCache.get(key);
  if (hit) return hit;
  const grid: readonly string[] = SPRITES[name];
  const canvas = document.createElement("canvas");
  canvas.width = grid[0].length;
  canvas.height = grid.length;
  const g = canvas.getContext("2d")!;
  grid.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const color = paletteColor(row[x], tint);
      if (!color) continue;
      g.fillStyle = color;
      g.fillRect(x, y, 1, 1);
    }
  });
  const url = canvas.toDataURL("image/png");
  urlCache.set(key, url);
  return url;
}

export interface SpriteOptions {
  /** Tint color (hex). */
  color?: string;
  /** Screen pixels per sprite pixel (see `syncPixelScale`). */
  scale?: 1 | 2 | 3 | 4;
  /** Extra class names. */
  cls?: string;
}

/** `<img>` markup for a sprite, sized on the device-pixel grid. */
export function sprite(name: SpriteName, opts: SpriteOptions = {}): string {
  const { color = UI_COLORS.white, scale = 2, cls = "" } = opts;
  const grid: readonly string[] = SPRITES[name];
  return (
    `<img class="px ${cls}" alt="" draggable="false" src="${spriteUrl(name, color)}" ` +
    `style="--w:${grid[0].length};--h:${grid.length};--px:var(--px${scale})" />`
  );
}

