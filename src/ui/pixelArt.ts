/** Filled pixel disc with a one-pixel ring, used for round tree nodes. */
function ringGrid(size: number, fill: string): string[] {
  const c = (size - 1) / 2;
  const outer = size / 2;
  const inner = outer - 1.45;
  const rows: string[] = [];
  for (let y = 0; y < size; y++) {
    let row = "";
    for (let x = 0; x < size; x++) {
      const d = Math.hypot(x - c, y - c);
      row += d > outer ? "." : d > inner ? "#" : fill;
    }
    rows.push(row);
  }
  return rows;
}

